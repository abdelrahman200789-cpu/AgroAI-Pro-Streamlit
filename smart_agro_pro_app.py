def refresh_engines():
    ke.reload()
    ir_sys.rebuild()


def log_action(message):
    fm.log_event(message)


def make_pdf(title, sections):
    """Create a small PDF report with project, date, inputs and results."""
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4, rightMargin=1.8 * cm, leftMargin=1.8 * cm,
        topMargin=1.8 * cm, bottomMargin=1.8 * cm
    )
    styles = getSampleStyleSheet()
    story = [Paragraph("AgroAI Pro", styles["Title"]), Paragraph(title, styles["Heading2"]), Spacer(1, 8)]
    meta = [
        ["Project", "AgroAI Pro — Smart Farming Advisor System"],
        ["Prepared by", TEAM_NAME],
        ["Generated", datetime.datetime.now().strftime("%Y-%m-%d %H:%M")],
    ]
    table = Table(meta, colWidths=[3.2 * cm, 12.5 * cm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e5f5ec")),
        ("TEXTCOLOR", (0, 0), (-1, -1), colors.HexColor("#17202a")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("PADDING", (0, 0), (-1, -1), 7),
    ]))
    story.extend([table, Spacer(1, 14)])
    for heading, body in sections:
        story.append(Paragraph(str(heading), styles["Heading3"]))
        if isinstance(body, list):
            for item in body:
                story.append(Paragraph("• " + str(item), styles["BodyText"]))
                story.append(Spacer(1, 4))
        else:
            safe_body = str(body).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(safe_body.replace("\n", "<br/>"), styles["BodyText"]))
        story.append(Spacer(1, 10))
    story.append(Paragraph(
        "Notice: This report is generated by a student prototype. It is informational only, "
        "not an official agricultural diagnosis, certification, or substitute for local expert advice.",
        styles["Italic"]
    ))
    doc.build(story)
    return buffer.getvalue()


